"""Batch 5 (split "test6"): 60 rules written by design principles learned on the development pool (rules_round6.py),
before any model answered them. No rule is chosen, dropped or reworded by a model's answers; only the engine check may
correct a label. Imported by rules.py.

Principles:
  1. Most conflict rules are passive: nobody acts on the scene, only time or weather passes.
  2. The real-world option states what really happens over that period, as a mild, believable change, not destruction.
  3. Question text avoids game-only words.
  4. The third option holds in neither world and is not absurd.
  5. Consistent rules are processes the game does simulate, often next to a conflict rule with a similar look, so that
     "nothing ever changes" or "the game exception applies" is not a safe answer.
Each rule carries `act`: "passive" (nobody acts) or "action" (something is done to the scene).
"""
